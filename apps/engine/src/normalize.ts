/**
 * Нормализует сырой текст Telegram-сообщения перед извлечением структуры
 * (числа/направление/символ). Действия: lowercase, `ё→е`, `э→е` (в дампе
 * встречаются оба варианта — «тэйк»/«тейк», «объём»/«объем»), схлопывание
 * повторяющихся пробельных символов в один обычный пробел, обрезка краёв.
 *
 * Порядок и почему это безопасно для остального пайплайна:
 * - normalize() рассчитан на вызов ПЕРВЫМ, до parseNumbers/splitKeycaps/
 *   resolveSymbol/extractSide/extractCoins — symbol-resolver.ts вызывает его
 *   сам на своём входе, так что снаружи достаточно передавать сырой текст как есть.
 * - Цифры и keycap-эмодзи (1️⃣, 2️⃣…) лоуэркейс и замена ё/э не затрагивают —
 *   splitKeycaps() одинаково работает что до, что после normalize().
 * - `\s+` матчит в том числе неразрывный (U+00A0) и узкий неразрывный (U+202F)
 *   пробелы, но схлопывание сводит любую их последовательность к ОДНОМУ обычному
 *   U+0020, который сам входит в набор разделителей тысяч parseNumbers() —
 *   поэтому "62 000$" с любым из трёх пробелов после normalize() всё ещё
 *   парсится в 62000, а не разваливается на два числа.
 */
export function normalize(text: string): string {
  return text
    .toLowerCase()
    .replace(/ё/g, 'е')
    .replace(/э/g, 'е')
    .replace(/\s+/g, ' ')
    .trim()
}
