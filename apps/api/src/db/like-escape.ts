/**
 * Экранирует спецсимволы LIKE/ILIKE (`%`/`_` — wildcard'ы; `\` — сам символ экранирования по
 * умолчанию у Postgres) перед подстановкой ПОЛЬЗОВАТЕЛЬСКОГО `q` в шаблон `%...%`
 * (actions.service.ts/positions.service.ts). Без этого, например, `q='60_000'` матчил бы и
 * "60x000" (`_` — wildcard "любой один символ"), а `q='%'` — вообще все строки подряд. Порядок
 * замен важен: сам `\` экранируется ПЕРВЫМ, иначе появившиеся на шаге `%`/`_` обратные слэши
 * задвоились бы повторно.
 */
export function escapeLikePattern(value: string): string {
  return value.replace(/\\/g, '\\\\').replace(/%/g, '\\%').replace(/_/g, '\\_')
}
